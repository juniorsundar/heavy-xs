-- Generates src/plugin_syms.rs: every Lua symbol a native plugin may resolve through
-- the `XL` resolver passed to luaopen_lite_xl_<name>(L, XL).
--
-- The source of truth is the header plugins compile against, not the C table in
-- src/api/system.c: that table is a hand-kept copy and has drifted (it lacks the 5.4.6
-- name `lua_closethread`, so a plugin calling it gets the header's exit(1) stub).
--
--   lua scripts/rust-port/gen-plugin-syms.lua           write the file
--   lua scripts/rust-port/gen-plugin-syms.lua --check   fail if it is out of date
local header_path = "resources/include/lite_xl_plugin_api.h"
local out_path = "src/plugin_syms.rs"

local f = assert(io.open(header_path, "rb")); local header = f:read("a"); f:close()

local names, seen = {}, {}
for name in header:gmatch("SYMBOL_DECLARE[_VARARG]*%s*%b()") do
  -- SYMBOL_DECLARE(ret, name, args...) : the name is the second argument.
  local second = name:match("%(%s*[^,]-,%s*([%w_]+)")
  if second and not seen[second] and second:match("^lua") then
    seen[second] = true
    names[#names + 1] = second
  end
end

-- Not in the header, but exposed by the C resolver since the plugin API was introduced.
local legacy = { "api_load_libs" }
for _, n in ipairs(legacy) do
  if not seen[n] then seen[n] = true; names[#names + 1] = n end
end
table.sort(names)
assert(#names > 140, "suspiciously few symbols: " .. #names)

local out = {
  "// @generated by scripts/rust-port/gen-plugin-syms.lua from " .. header_path .. ". Do not edit.",
  "//",
  "// Only the addresses matter, so each symbol is declared with a placeholder signature.",
  "#![allow(clashing_extern_declarations)]",
  "",
  "extern \"C\" {",
}
for _, n in ipairs(names) do out[#out + 1] = ("    fn %s();"):format(n) end
out[#out + 1] = "}"
out[#out + 1] = ""
out[#out + 1] = ("/// %d symbols, sorted by name."):format(#names)
out[#out + 1] = "pub static SYMBOLS: [(&str, unsafe extern \"C\" fn()); " .. #names .. "] = ["
for _, n in ipairs(names) do out[#out + 1] = ('    ("%s", %s),'):format(n, n) end
out[#out + 1] = "];"
out[#out + 1] = ""
local text = table.concat(out, "\n")

if arg[1] == "--check" then
  local g = io.open(out_path, "rb")
  local current = g and g:read("a"); if g then g:close() end
  if current ~= text then io.stderr:write(out_path .. " is out of date\n"); os.exit(1) end
  print(out_path .. " is up to date (" .. #names .. " symbols)")
else
  local g = assert(io.open(out_path, "wb")); g:write(text); g:close()
  print("wrote " .. out_path .. " (" .. #names .. " symbols)")
end
